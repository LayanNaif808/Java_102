public class Ex2 {

    // Method that calculates and returns the square of a number (x * x)
    public static int square(int x) { 

        return x * x; 

    }

    public static void main(String[] args) { 

        // Call the square method for 4 and 3, then print their sum
        System.out.println(square(4) + square(3));

    }
}

